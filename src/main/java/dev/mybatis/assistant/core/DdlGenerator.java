package dev.mybatis.assistant.core;

import java.util.*;
import java.util.stream.Collectors;

public final class DdlGenerator {
    private DdlGenerator(){}
    public static String generate(Schema.Table table,boolean mysql){
        if(table.columns().isEmpty())throw new IllegalArgumentException("未找到可转换的字段");
        List<String> lines=new ArrayList<>();
        for(var c:table.columns())lines.add("  "+Schema.quote(c.name(),mysql)+" "+c.sqlType().toUpperCase(Locale.ROOT)+(c.nullable()?"":" NOT NULL")+(c.autoIncrement()?mysql?" AUTO_INCREMENT":" GENERATED BY DEFAULT AS IDENTITY":""));
        var keys=table.columns().stream().filter(Schema.Column::primaryKey).map(c->Schema.quote(c.name(),mysql)).toList();
        if(!keys.isEmpty())lines.add("  PRIMARY KEY ("+String.join(", ",keys)+")");
        return "CREATE TABLE "+Schema.quote(table.name(),mysql)+" (\n"+String.join(",\n",lines)+"\n);\n";
    }
    public static String sqlType(String javaType){
        return switch(javaType){
            case "long","java.lang.Long"->"BIGINT";
            case "int","short","byte","java.lang.Integer","java.lang.Short","java.lang.Byte"->"INTEGER";
            case "boolean","java.lang.Boolean"->"BOOLEAN";
            case "float","double","java.lang.Float","java.lang.Double"->"DOUBLE";
            case "java.math.BigDecimal","java.math.BigInteger"->"DECIMAL(19,4)";
            case "java.lang.String","char","java.lang.Character"->"VARCHAR(255)";
            case "java.time.LocalDate","java.sql.Date"->"DATE";
            case "java.time.LocalDateTime","java.time.Instant","java.util.Date","java.sql.Timestamp"->"TIMESTAMP";
            case "java.time.LocalTime","java.sql.Time"->"TIME";
            case "byte[]"->"BLOB";
            default->null;
        };
    }
}
